now = 22500;
ticks.forEach(tick => tick());
assert.equal(workout.elapsed(), 8, 'Elapsed time must exclude pauses and preserve fractional seconds');
workout.finishSession();
assert.deepEqual(finished, { id: 'session', duration: 8 });
assert.equal(ticks.size, 0, 'Stop must clear the timer');
const failed = new exportsObject.WorkoutComponent();
failed.ngOnInit();
failStart = true;
failed.play();
assert.equal(failed.running(), false);
assert.equal(failed.saving(), false);
assert.ok(failed.error());
workout.ngOnDestroy();
failStart = false;
const series = new exportsObject.WorkoutComponent();
series.ngOnInit();
series.configureTimer('work', '30');
series.configureTimer('rest', '10');
series.startSeries(1);
assert.equal(series.phase(), 'idle', 'Series must start in order');
series.startSeries(0);
assert.equal(series.phase(), 'work');
now += 5000;
ticks.forEach(tick => tick());
series.pause();
now += 50000;
series.play();
now += 3000;
ticks.forEach(tick => tick());
assert.equal(series.phaseElapsed(), 8, 'Work timer excludes pauses');
failSet = true;
series.completeSet(0, '20', '8');
assert.equal(series.completed().size, 0, 'Failed save must not complete a set');
assert.equal(series.phase(), 'work', 'Failed save must not start rest');
now += 2000;
failSet = false;
series.completeSet(0, '20', '8');
assert.equal(savedSets[0].durationSeconds, 8, 'Retry must preserve stopped duration');
assert.equal(series.completed().has(0), true);
assert.equal(series.phase(), 'rest', 'Stop must automatically start rest');
series.startSeries(1);
assert.equal(series.phase(), 'rest', 'Play must wait until rest ends');
now += 4000;
ticks.forEach(tick => tick());
series.pause();
now += 20000;
series.play();
now += 6000;
ticks.forEach(tick => tick());
assert.equal(series.phase(), 'idle', 'Rest must finish automatically, excluding pauses');
series.startSeries(1);
now += 35000;
ticks.forEach(tick => tick());
assert.equal(series.phase(), 'work', 'Reaching the work target must wait for explicit Stop');
series.completeSet(1, '22.5', '10');
assert.equal(savedSets[1].actualRestSeconds, 10);
assert.equal(savedSets[1].durationSeconds, 35);
series.endRest();
series.configureTimer('rest', '0');
series.startSeries(2);
series.completeSet(2, '25', '8');
assert.equal(series.phase(), 'idle', 'Zero rest must allow the next action immediately');
assert.equal(series.completed().size, 3);
series.ngOnDestroy();
const controls = new exportsObject.WorkoutComponent();
controls.ngOnInit();
controls.startSeries(0);
now += 5500;
ticks.forEach(tick => tick());
