assert.equal(controls.phaseMilliseconds(), 5500, 'Series pause preserves milliseconds');
assert.equal(controls.elapsed(), 15, 'Series pause must leave total session timer running');
controls.pause();
now += 10000;
controls.play();
now += 10000;
ticks.forEach(tick => tick());
assert.equal(controls.phaseElapsed(), 5, 'Global resume must preserve individual series pause');
controls.startSeries(0);
