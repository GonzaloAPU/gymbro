const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const { of, throwError } = require('rxjs');

const source = fs.readFileSync('frontend/src/app/components/workout.component.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, experimentalDecorators: true } }).outputText;
let now = 0;
let starts = 0;
let finished;
let failStart = false;
let failSet = false;
const savedSets = [];
const ticks = new Set();
const routineService = { getAll: () => of([{ active: true, name: 'Prueba', days: [{ id: 'day', name: 'Sesión del plan', schedule: [{weekday: new Date().getDay(),start:'08:00',end:'09:00'}], exercises: [{ exercise: { id: 'exercise', name: 'Sentadilla', muscleGroup: 'Piernas' }, targetSets: 3, minReps: 8, maxReps: 10, restSeconds: 90 }] }] }]) };
const sessionService = { start: () => { starts++; return failStart ? throwError(() => new Error('offline')) : of({ id: 'session' }); }, finish: (id, duration) => { finished = { id, duration }; return of({}); }, addExercise: () => of({ id: 'performed' }), addSet: (_session, _exercise, data) => { if (failSet) return throwError(() => new Error('offline')); savedSets.push(data); return of({}); } };
sessionService.replaceSet = (_session, _exercise, data) => { if (failSet) return throwError(() => new Error('offline')); const index = savedSets.findIndex(row => row.setNumber === data.setNumber); assert.ok(index >= 0); savedSets[index] = data; return of({}); };
let navigations = 0;
const router = { navigateByUrl: path => { navigations++; assert.equal(path, '/progreso'); } };
const exportsObject = {};
vm.runInNewContext(compiled, {
  exports: exportsObject,
  require: name => {
    if (name === '@angular/core') return {
      Component: () => target => target, Input: () => () => {},
      signal: initial => { let value = initial; const read = () => value; read.set = next => { value = next; }; return read; },
      inject: token => token === 'routine' ? routineService : token === 'session' ? sessionService : router,
    };
    if (name === '@angular/router') return { Router: 'router' };
    if (name.includes('routine.service')) return { RoutineService: 'routine' };
    if (name.includes('session.service')) return { SessionService: 'session' };
    return require(name);
  },
  performance: { now: () => now },
  window: { setInterval: tick => { ticks.add(tick); return tick; }, clearInterval: tick => ticks.delete(tick) },
});
const workout = new exportsObject.WorkoutComponent();
workout.ngOnInit();
assert.equal(starts, 0, 'Opening the page must not create a session');
